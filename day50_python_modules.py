# 📦 All imports go at the very top!
import random
import math as m

# Task 1: The Math Module (Using the 'm' alias!)
print(m.sqrt(64))

# Task 2: The Random Module (Generating Flight Delays)
print(random.randint(10, 60))

# Task 3: Random Choice from a List
destinations = ["Dubai", "Paris", "London"]
print(random.choice(destinations))

# Task 4: Aliasing (Nicknames)
print(m.pi)

